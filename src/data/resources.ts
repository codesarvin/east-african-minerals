export function getResourceBySlug(slug: string): Resource | undefined {
  return resources.find(resource => resource.slug === slug);
}

export function getResourcesByCategory(category: ResourceCategory): Resource[] {
  return resources.filter(resource => resource.category === category);
}

export function getRelatedResources(currentSlug: string, limit = 3): Resource[] {
  const current = getResourceBySlug(currentSlug);
  if (!current) return [];
  
  return resources
    .filter(resource => resource.slug !== currentSlug)
    .filter(resource => 
      resource.category === current.category ||
      resource.tags.some(tag => current.tags.includes(tag))
    )
    .slice(0, limit);
}
